"""急症识别（Triage）—— 必须优先于用药门禁执行。

为什么单独抽一层：
    用药门禁的设计是"确认后放行"，急症的设计是"先救命"。旧版 `precheck` 只做
    用药意图识别，于是"误服了半瓶安眠药""吃了头孢又喝酒"这类问题因为含"药/头孢"
    被拦成"用药咨询"，用户看到的回复是"未获得确认前我不能给出结论"——既没有 120，
    也没有急救指引。这是安全优先级问题，不是关键词问题。

判定原则：宁可多报，不可漏报。
    - 组合条件（胸痛 + 冷汗/呼吸困难、头孢 + 酒）单独处理，避免把"头孢和酒能一起吗"
      这种询问误判成"正在发生的反应"；
    - 命中即返回原因，调用方直接给出急救话术，不再走工具与确认流程。
"""

from __future__ import annotations

from typing import Optional

# 等待救援期间的针对性提示（键 = detect_emergency 的返回值）
EMERGENCY_TIPS = {
    "疑似急性心血管事件": "让患者保持静卧，不要自行走动、不要自行服药或进食。",
    "疑似脑卒中": "记录发病时间（对溶栓决策很关键），不要自行服药，不要喂水。",
    "抽搐/惊厥": "移开周围硬物，不要往嘴里塞任何东西，记录抽搐持续时间。",
    "活动性出血": "用干净纱布持续按压伤口止血，不要反复松开查看。",
    "意识障碍": "让患者侧卧防止呕吐物误吸，不要强行喂水喂药。",
    "药物过量/误服": "保留药品包装或呕吐物样本，一并交给医生。",
    "双硫仑样反应风险": "立即停止饮酒，保持坐位或半卧位，不要自行催吐。",
    "产科急症": "让孕妇平卧、减少搬动，尽快送医。",
    "呼吸困难": "保持坐位、松开衣领，不要平躺。",
    "自伤风险": "不要独处，联系身边可信任的人陪同，必要时拨打 120。",
    "动物咬伤": "用流动清水和肥皂水冲洗伤口至少 15 分钟，尽快就医接种狂犬疫苗。",
}


def _any(text: str, words: tuple) -> bool:
    return any(word in text for word in words)


def detect_emergency(text: str) -> Optional[str]:
    """命中急症规则时返回原因，否则返回 None。

    顺序即优先级：心脑血管 > 抽搐/出血/意识 > 中毒/过敏 > 产科 > 呼吸 > 自伤 > 咬伤。
    """
    if not text:
        return None

    # 1) 胸痛 + 伴随症状（单纯"心慌胸闷、爬楼喘"不应命中）
    if _any(text, ("胸口剧痛", "胸痛", "胸骨后疼痛", "心前区疼痛")) and _any(
        text, ("冷汗", "呼吸困难", "喘不上气", "濒死", "压榨")
    ):
        return "疑似急性心血管事件"

    # 2) 卒中：单侧无力 / 言语含糊
    if _any(text, ("一侧胳膊抬不起来", "一侧肢体无力", "半身不遂", "说话含糊", "口角歪斜")):
        return "疑似脑卒中"

    if _any(text, ("抽搐", "惊厥")):
        return "抽搐/惊厥"

    if _any(text, ("流血不止", "大出血", "一直流血", "血止不住", "出血不止")):
        return "活动性出血"

    if _any(text, ("叫不醒", "昏迷", "意识不清", "晕倒", "意识模糊")):
        return "意识障碍"

    if _any(text, ("误服", "误食", "吃错药", "过量服药", "吃多了药", "吃了半瓶")):
        return "药物过量/误服"

    # 3) 头孢/甲硝唑 + 酒：要排除"能不能一起"这种询问
    if _any(text, ("头孢", "甲硝唑")) and _any(text, ("酒",)) and not _any(
        text, ("能不能", "可以", "能一起", "能喝", "一起吗")
    ):
        return "双硫仑样反应风险"

    if "孕妇" in text and _any(text, ("出血", "肚子疼", "腹痛", "破水")):
        return "产科急症"

    if _any(text, ("喘不上气", "呼吸困难", "窒息")):
        return "呼吸困难"

    if _any(text, ("自杀", "轻生", "不想活")):
        return "自伤风险"

    if _any(text, ("被狗咬", "被猫咬", "动物咬伤")):
        return "动物咬伤"

    return None


def build_emergency_answer(reason: str) -> str:
    """急症统一话术：先 120，再给等待救援的针对性提示。"""
    lines = [
        "⚠️ 您描述的情况可能是需要立即处理的紧急情况，请不要等待线上回复。",
        "请立即拨打 120 急救电话（或让身边的人拨打），并尽快前往最近医院的急诊科。",
    ]
    tip = EMERGENCY_TIPS.get(reason)
    if tip:
        lines.append(f"等待救援期间：{tip}")
    lines.append("以上仅为急救方向提示，具体判断与处置以急救人员和急诊医生为准。")
    return "\n\n".join(lines)
